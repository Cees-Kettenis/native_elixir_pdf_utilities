defmodule NativeElixirPdfUtilities.HtmlToPdf.LinkAnnotationAdmissionTest do
  use ExUnit.Case, async: false

  alias NativeElixirPdfUtilities.HtmlToPdf.PdfWriter
  alias NativeElixirPdfUtilities.{HtmlToPdf, Limits, Operation}
  alias NativeElixirPdfUtilities.Pdf.Reader

  alias NativeElixirPdfUtilities.Validators.{
    HtmlValidator,
    ResourceBudgetValidator,
    WriterValidator
  }

  setup do
    original = Limits.effective()
    on_exit(fn -> Limits.install(original) end)
    %{limits: original}
  end

  test "raising the output allowance preserves a link rendered at the source byte limit", ctx do
    uri = "https://example.com/"
    html = ~s(<p><a href="#{uri}">Hello</a></p>)
    opts = [system_font_discovery: false]

    {{:ok, expected}, source_bytes} =
      Operation.run(__MODULE__, :render, fn ->
        {HtmlToPdf.render(html, opts), ResourceBudgetValidator.snapshot().max_input_bytes}
      end)

    assert byte_size(expected) < source_bytes - 1

    for output <- [source_bytes - 1, source_bytes, source_bytes + 1, ctx.limits.max_output_bytes] do
      Limits.install(%{ctx.limits | max_input_bytes: source_bytes, max_output_bytes: output})
      assert {:ok, ^expected} = HtmlToPdf.render(html, opts)
      assert {:ok, %{document: document, pages: [page]}} = Reader.read_validated(expected)
      [link] = page.dictionary["Annots"]
      assert {:ok, %{"A" => %{"URI" => {:string, ^uri}}}} = Reader.resolve(document, link)
    end

    for {key, bytes} <- [
          max_input_bytes: byte_size(html) - 1,
          max_output_bytes: byte_size(expected) - 1
        ] do
      Limits.install(Map.put(ctx.limits, key, bytes))
      assert {:error, {:resource_limit_exceeded, diagnostic}} = HtmlToPdf.render(html, opts)
      assert diagnostic.operation == :render
      assert diagnostic.message =~ Atom.to_string(key)
    end
  end

  test "annotation bytes include literal escapes and accumulate before serialization", ctx do
    for {uri, encoded_bytes} <- [
          {nil, 0},
          {"", 0},
          {"plain", 5},
          {"a(b)\\c\r\nd\ne\rf", 18}
        ] do
      allowance = encoded_bytes + 4
      Limits.install(%{ctx.limits | max_input_bytes: allowance})

      assert :ok =
               HtmlValidator.with_render_budget(fn ->
                 WriterValidator.reserve_annotation_bytes(["<<", ">>"], uri)
               end)

      Limits.install(%{ctx.limits | max_input_bytes: allowance - 1})

      assert {:error, {:resource_limit_exceeded, diagnostic}} =
               HtmlValidator.with_render_budget(fn ->
                 WriterValidator.reserve_annotation_bytes(["<<", ">>"], uri)
               end)

      assert diagnostic.stage == :writer and diagnostic.message =~ "max_input_bytes"
    end

    Limits.install(%{ctx.limits | max_input_bytes: 19})

    assert {:error, {:resource_limit_exceeded, _}} =
             HtmlValidator.with_render_budget(fn ->
               WriterValidator.reserve_annotation_bytes(["fixed"], "12345")
               WriterValidator.reserve_annotation_bytes(["fixed"], "12345")
             end)
  end

  test "long repeated links stop at the aggregate annotation byte allowance", ctx do
    uri = "https://example.com/" <> String.duplicate("(path)", 1_000)

    box = %{
      type: :text,
      text: "Link",
      x: 0,
      y: 10,
      width: 20,
      height: 10,
      font: "Helvetica",
      font_size: 10,
      color: {0, 0, 0},
      link_url: uri
    }

    pages = [%{size: {100, 100}, boxes: List.duplicate(box, 16)}]
    Limits.install(%{ctx.limits | max_input_bytes: 12_000})
    assert {:error, {:resource_limit_exceeded, diagnostic}} = PdfWriter.render(pages)
    assert diagnostic.stage == :writer and diagnostic.message =~ "max_input_bytes"

    Limits.install(ctx.limits)
    assert {:ok, pdf} = PdfWriter.render(pages)
    assert {:ok, _} = Reader.read_validated(pdf)
    assert length(:binary.matches(pdf, "/Subtype /Link")) == 16
    assert pdf =~ "\\(path\\)"
  end

  test "generated bytes and annotation allowance also respect a lower reader input limit", ctx do
    pages = [%{size: {100, 100}, boxes: []}]
    assert {:ok, pdf} = PdfWriter.render(pages)

    for bytes <- [byte_size(pdf) - 1, byte_size(pdf)] do
      Limits.install(%{ctx.limits | max_input_bytes: bytes})

      case bytes == byte_size(pdf) do
        true ->
          assert {:ok, output} = PdfWriter.render(pages)
          assert {:ok, _} = Reader.read_validated(output)

        false ->
          assert {:error, {:resource_limit_exceeded, diagnostic}} = PdfWriter.render(pages)
          assert diagnostic.stage == :writer and diagnostic.message =~ "max_input_bytes"
      end
    end

    Limits.install(%{ctx.limits | max_input_bytes: 9})

    assert {:error, {:resource_limit_exceeded, diagnostic}} =
             HtmlValidator.with_render_budget(fn ->
               WriterValidator.reserve_annotation_bytes(["fixed"], "12345")
             end)

    assert diagnostic.message =~ "max_input_bytes"
  end
end
