#!/usr/bin/env python3
"""Generate immutable MathML Core B.1 tables from the pinned local snapshot.

Usage: scripts/fixtures/generate-math-operator-dictionary.py [snapshot] [--check]
No network access or third-party Python dependencies are used.
"""
import hashlib
import html
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
SOURCE = 'https://www.w3.org/TR/2025/CR-mathml-core-20250624/'
SOURCE_SHA256 = 'f61ebea74ba54c489646e6969983ef977f448c26602edff75ec4e3ba77216373'
source_path = Path(next((arg for arg in sys.argv[1:] if arg != '--check'),
                        ROOT / 'tmp/references/mathml-core.html'))
source = source_path.read_bytes()
if hashlib.sha256(source).hexdigest() != SOURCE_SHA256:
    raise SystemExit('Snapshot SHA-256 differs from the pinned MathML Core source')
snapshot = source.decode('utf-8')

def figure(name):
    match = re.search(r'<figure id="' + name + r'">(.*?)</figure>', snapshot, re.S)
    if not match:
        raise SystemExit('Missing source figure: ' + name)
    return match.group(1)

def plain(value):
    return html.unescape(re.sub(r'<[^>]*>', '', value)).strip()

def rows(name):
    return [[plain(cell) for cell in re.findall(r'<td>(.*?)</td>', row, re.S)]
            for row in re.findall(r'<tr>(.*?)</tr>', figure(name), re.S)
            if '<td>' in row]

def points(value):
    result = []
    for first, last in re.findall(r'U\+([0-9A-F]+)(?:–U\+([0-9A-F]+))?', value):
        result.extend(range(int(first, 16), int(last or first, 16) + 1))
    return result

def atom(value):
    return ':' + re.sub(r'(?<!^)(?=[A-Z])', '_', value).lower()

special = dict(rows('operator-dictionary-compact-special-tables'))
ascii_pairs = re.findall(r"'([^']+)'", special['Operators_2_ascii_chars'])
assert len(ascii_pairs) == 18
categories = rows('operator-dictionary-categories-values')
entries = []
for content, category in rows('operator-dictionary-category-table'):
    form = re.search(r'in (infix|prefix|postfix) form', content).group(1)
    entries.extend((cp, form, category) for cp in points(content))
assert len(entries) == 725 and len(set((cp, form) for cp, form, _ in entries)) == 725
# The normative algorithm uses the hexadecimal table except for L/M.
# Check both representations before generating the equivalent direct lookup.
encodings = {int(encoding, 16): category
             for category, _, encoding, _, _, _ in categories
             if encoding.startswith('0x')}
compact = []
compact_text = figure('operator-dictionary-categories-hexa-table').split('<figcaption>')[0]
for first, last in re.findall(r'0x([0-9A-F]+)(?:–0x([0-9A-F]+))?', compact_text):
    for entry in range(int(first, 16), int(last or first, 16) + 1):
        key = entry % 0x4000
        codepoint = key % 0x1000
        if codepoint >= 0x400:
            codepoint += 0x1C00
        compact.append((codepoint, ['infix', 'prefix', 'postfix'][key // 0x1000],
                        encodings[entry // 0x1000]))
assert len(compact) == 716
assert set(compact) == {entry for entry in entries if entry[2] not in ['L', 'M']}
fences = points(special['Operators_fence'])
separators = points(special['Operators_separator'])
axes = points(figure('inline-stretch-axis').split('<figcaption>')[0])
assert (len(fences), len(separators), len(axes)) == (61, 3, 246)

out = f'''defmodule NativeElixirPdfUtilities.HtmlToPdf.MathOperatorDictionary do
  @moduledoc false

  # Generated by scripts/fixtures/generate-math-operator-dictionary.py; do not edit.
  # Normative MathML Core B.1 figures 24, 25, 26 and 28.
  # Generation verifies figure 25 against the compact figure 27 encoding.
  # The UTF-16 and combining-overlay rules live in MathOperatorValidator.
  @source_url "{SOURCE}"
  @source_sha256 "{SOURCE_SHA256}"

  @categories %{{
'''
for category, _, _, left, right, properties in categories:
    out += f'    {atom(category)} => %{{lspace: {left.removesuffix("em")}, rspace: {right.removesuffix("em")}'
    for prop in ['stretchy', 'symmetric', 'largeop', 'movablelimits']:
        out += f', {prop}: {str(prop in properties.split()).lower()}'
    out += '},\n'
out += '  }\n\n  @entries %{\n'
for cp, form, cat in sorted(entries):
    out += f'    {{0x{cp:04X}, :{form}}} => {atom(cat)},\n'
out += '  }\n\n  @data %{\n    categories: @categories,\n    entries: @entries,\n    ascii_pairs: %{\n'
for i, pair in enumerate(ascii_pairs):
    out += f'      "{pair}" => 0x{0x320+i:04X},\n'
out += '    },\n'
for name, values in [('fences', fences), ('separators', separators), ('inline_axes', axes)]:
    out += f'    {name}: MapSet.new([' + ', '.join(f'0x{cp:04X}' for cp in values) + ']),\n'
out += '''    source_url: @source_url,
    source_sha256: @source_sha256
  }

  @doc false
  @spec data() :: map()
  def data, do: @data
end
'''
formatted = subprocess.run(['mise', 'exec', '--', 'mix', 'format', '--stdin-filename',
                            'lib/html_to_pdf/math_operator_dictionary.ex', '-'],
                           cwd=ROOT, input=out, text=True, capture_output=True, check=True).stdout
output = ROOT / 'lib/html_to_pdf/math_operator_dictionary.ex'
if '--check' in sys.argv:
    if not output.exists() or output.read_text() != formatted:
        raise SystemExit('Generated operator dictionary differs; regenerate it')
else:
    output.write_text(formatted)
print('MathML Core dictionary: 725 category entries, 246 inline axes; pinned SHA-256 verified')
