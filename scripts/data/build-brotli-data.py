"""Generate RFC 7932 dictionary/context/transform data from google/brotli v1.2.0.

Development only: pass the directory containing dictionary.bin, Context.java,
Transform.java and LICENSE from that tag. No network access or runtime downloads.
"""
from pathlib import Path
import sys,re,json,hashlib,base64
root=Path(__file__).resolve().parents[2]
source=Path(sys.argv[1])
def java_string(path,name):
    text=path.read_text()
    expression=re.search(r'private static final String '+name+r'\s*=\s*((?:"(?:[^"\\]|\\.)*"\s*(?:\+\s*)?)+);',text,re.S)[1]
    return ''.join(json.loads(token) for token in re.findall(r'"(?:[^"\\]|\\.)*"',expression))
prefix=java_string(source/'Transform.java','PREFIX_SUFFIX_SRC')
pieces=[bytes(ord(char) for char in part) for part in prefix.split('#')[:-1]]
transforms=java_string(source/'Transform.java','TRANSFORMS_SRC')
transforms=[tuple(ord(c)-32 for c in transforms[i:i+3]) for i in range(0,len(transforms),3)]
assert len(pieces)==50 and len(transforms)==121
utfmap=java_string(source/'Context.java','UTF_MAP');rle=java_string(source/'Context.java','UTF_RLE')
lookup=[0]*2048
for i in range(256):lookup[i]=i&63;lookup[512+i]=i>>2;lookup[1792+i]=2+(i>>6)
for i in range(128):lookup[1024+i]=4*(ord(utfmap[i])-32)
for i in range(64):lookup[1152+i]=i&1;lookup[1216+i]=2+(i&1)
offset=1280
for k,c in enumerate(rle):
    for i in range(ord(c)-32):lookup[offset]=k&3;offset+=1
assert offset==1536
for i in range(16):lookup[1792+i]=1;lookup[2032+i]=6
lookup[1792]=0;lookup[2047]=7
for i in range(256):lookup[1536+i]=lookup[1792+i]<<3
sizebits=[0,0,0,0,10,10,11,11,10,10,10,10,10,9,9,8,7,7,8,7,7,6,6,5,5]
offsets=[0]*25;end=0
for length in range(4,25):offsets[length]=end;end+=length*(1<<sizebits[length])
dictionary=(source/'dictionary.bin').read_bytes();assert len(dictionary)==end==122784
folder=root/'priv/fonts/brotli';folder.mkdir(exist_ok=True)
(folder/'dictionary.bin').write_bytes(dictionary)
(root/'priv/licenses/brotli-MIT.txt').write_bytes((source/'LICENSE').read_bytes())
manifest={'source':'https://github.com/google/brotli/tree/v1.2.0','license':'priv/licenses/brotli-MIT.txt','files':{name:hashlib.sha256((source/name).read_bytes()).hexdigest() for name in ['dictionary.bin','Context.java','Transform.java','LICENSE']}}
(root/'scripts/data/brotli-source.json').write_text(json.dumps(manifest,indent=2)+'\n')
source_text='''defmodule NativeElixirPdfUtilities.HtmlToPdf.Font.BrotliData do
  @moduledoc false
  # RFC 7932, July 2016, Appendix A/B. Google Brotli v1.2.0, MIT.
  # Generated by scripts/data/build-brotli-data.py. Provenance: scripts/data/brotli-source.json.
  @external_resource Path.expand("../../../priv/fonts/brotli/dictionary.bin", __DIR__)
  @dictionary File.read!(@external_resource)
'''
source_text+='  @context Base.decode64!("'+base64.b64encode(bytes(lookup)).decode()+'")\n'
source_text+='  @prefixes {'+','.join('Base.decode64!("'+base64.b64encode(piece).decode()+'")' for piece in pieces)+'}\n'
source_text+='  @transforms {'+','.join('{'+','.join(map(str,triplet))+'}' for triplet in transforms)+'}\n'
source_text+='  @size_bits {'+','.join(map(str,sizebits))+'}\n'
source_text+='  @offsets {'+','.join(map(str,offsets))+'}\n'
for name,spec,value in [('dictionary','binary()','@dictionary'),('context','binary()','@context'),('prefixes','tuple()','@prefixes'),('transforms','tuple()','@transforms'),('size_bits','tuple()','@size_bits'),('offsets','tuple()','@offsets')]:
    source_text+=f'\n  @doc false\n  @spec {name}() :: {spec}\n  def {name}, do: {value}\n'
source_text+='end\n'
(root/'lib/html_to_pdf/font/brotli_data.ex').write_text(source_text)
