#!/usr/bin/env python3
"""Export ICU 78's CLDR quotation delimiters using Chromium's locale policy.

Reference: Chromium 152.0.7977.82 layout_locale.cc, GetQuotesDataForLanguage.
Requires the ICU 78 shared libraries. Regeneration does not affect render runtime.
"""
import ctypes
import json
from pathlib import Path

uc = ctypes.CDLL('libicuuc.so.78')
i18n = ctypes.CDLL('libicui18n.so.78')
status = ctypes.c_int32(0)
open_locales = uc.uloc_openAvailableByType_78
open_locales.restype = ctypes.c_void_p
open_locales.argtypes = [ctypes.c_int, ctypes.POINTER(ctypes.c_int32)]
next_locale = uc.uenum_next_78
next_locale.restype = ctypes.c_char_p
next_locale.argtypes = [ctypes.c_void_p, ctypes.c_void_p, ctypes.POINTER(ctypes.c_int32)]
open_data = i18n.ulocdata_open_78
open_data.restype = ctypes.c_void_p
open_data.argtypes = [ctypes.c_char_p, ctypes.POINTER(ctypes.c_int32)]
delimiter = i18n.ulocdata_getDelimiter_78
delimiter.argtypes = [ctypes.c_void_p, ctypes.c_int, ctypes.POINTER(ctypes.c_uint16), ctypes.c_int32, ctypes.POINTER(ctypes.c_int32)]
close_data = i18n.ulocdata_close_78
close_data.argtypes = [ctypes.c_void_p]
close_locales = uc.uenum_close_78
close_locales.argtypes = [ctypes.c_void_p]
locales = open_locales(0, ctypes.byref(status))
groups = {}
while locale := next_locale(locales, None, ctypes.byref(status)):
    error = ctypes.c_int32(0)
    data = open_data(locale, ctypes.byref(error))
    chars = []
    for kind in range(4):
        output = (ctypes.c_uint16 * 8)()
        length = delimiter(data, kind, output, 8, ctypes.byref(error))
        if error.value > 0 or length != 1:
            break
        chars.append(chr(output[0]))
    close_data(data)
    if len(chars) == 4:
        groups.setdefault(tuple(chars), []).append(locale.decode().replace('_', '-').lower())
close_locales(locales)

lines = ['defmodule NativeElixirPdfUtilities.HtmlToPdf.QuotationData do',
         '  @moduledoc false',
         '  # Generated by scripts/data/quotation/generate.py from ICU 78 CLDR data.',
         '  # Chromium 152 uses these four single-character delimiters and locale fallback.',
         '  @pairs Enum.reduce([']
for chars, names in sorted(groups.items()):
    pair = '[{' + json.dumps(chars[0], ensure_ascii=False) + ', ' + json.dumps(chars[1], ensure_ascii=False) + '}, {' + json.dumps(chars[2], ensure_ascii=False) + ', ' + json.dumps(chars[3], ensure_ascii=False) + '}]'
    lines.append('    {' + json.dumps(sorted(names), ensure_ascii=False) + ', ' + pair + '},')
lines += ['  ], %{}, fn {locales, pairs}, acc ->',
          '    Enum.reduce(locales, acc, &Map.put(&2, &1, pairs))',
          '  end)', '',
          '  @doc "Returns pinned CLDR quote pairs for the longest recognized locale prefix."',
          '  @spec pairs([String.t()]) :: [{String.t(), String.t()}]',
          '  def pairs(language) do',
          '    length(language)..1//-1',
          '    |> Enum.find_value(fn size -> Map.get(@pairs, language |> Enum.take(size) |> Enum.join("-")) end)',
          '    |> then(&(&1 || [{"“", "”"}, {"‘", "’"}]))',
          '  end', 'end', '']
target = Path(__file__).resolve().parents[3] / 'lib/html_to_pdf/quotation_data.ex'
target.write_text('\n'.join(lines))
print(f'{sum(map(len, groups.values()))} locales, {len(groups)} delimiter groups')
