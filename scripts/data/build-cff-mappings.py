"""Build CFF standard SID, charset and encoding data with fonttools 4.66.1.

The mappings are specified by Adobe Technical Note 5176, appendices A, B and C.
No downloads are performed. Keep the fontTools MIT notice with generated data.
"""
from pathlib import Path
import hashlib
import json
import shutil
from importlib.metadata import distribution
import fontTools
from fontTools import cffLib
from fontTools.encodings.StandardEncoding import StandardEncoding

root=Path(__file__).resolve().parents[2]
strings=cffLib.cffStandardStrings
sids={name:index for index,name in enumerate(strings)}
charsets=[[sids[name] for name in names] for names in [cffLib.cffISOAdobeStrings,cffLib.cffIExpertStrings,cffLib.cffExpertSubsetStrings]]
encoding=[sids[name] for name in StandardEncoding]
assert len(strings)==391 and [len(x) for x in charsets]==[229,166,87] and len(encoding)==256
payload=json.dumps({'strings':strings,'charsets':charsets,'encoding':encoding},separators=(',',':')).encode()
header=f'''defmodule NativeElixirPdfUtilities.HtmlToPdf.Font.CffData do
  @moduledoc false
  # Adobe Technical Note 5176, appendices A, B and C.
  # https://adobe-type-tools.github.io/font-tech-notes/pdfs/5176.CFF.pdf
  # Generated by scripts/data/build-cff-mappings.py with fonttools {fontTools.__version__}.
  # Mapping JSON SHA-256: {hashlib.sha256(payload).hexdigest()}
  # fontTools MIT notice: priv/licenses/cff-character-mappings-MIT.txt.
'''
source=header+"  @strings "+json.dumps(strings)+" |> List.to_tuple()\n"
source+="  @charsets {"+','.join('{'+','.join(map(str,x))+'}' for x in charsets)+"}\n"
source+="  @standard_encoding {"+','.join(map(str,encoding))+"}\n\n"
source+='''  @doc "Returns the 391 standard CFF SID strings."
  @spec standard_strings() :: tuple()
  def standard_strings, do: @strings

  @doc "Returns the ISOAdobe, Expert and ExpertSubset SID arrays, including .notdef."
  @spec predefined_charsets() :: {tuple(), tuple(), tuple()}
  def predefined_charsets, do: @charsets

  @doc "Returns the 256 StandardEncoding byte-to-SID entries, with .notdef for undefined codes."
  @spec standard_encoding() :: tuple()
  def standard_encoding, do: @standard_encoding
end
'''
(root/'lib/html_to_pdf/font/cff_data.ex').write_text(source)
d=distribution('fonttools')
license_path=next(d.locate_file(p) for p in d.files if str(p).endswith('licenses/LICENSE'))
shutil.copyfile(license_path,root/'priv/licenses/cff-character-mappings-MIT.txt')
